import {chromium} from '@playwright/test';
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/#/engines/turbofan');
 await page.getByRole('heading',{name:'Inside the turbofan.'}).waitFor();
 await page.getByRole('button',{name:'Command palette'}).click();
 await page.getByRole('dialog',{name:'Command palette'}).waitFor();
 await page.getByRole('textbox',{name:'Search commands'}).fill('Measure 3D');
 await page.getByRole('button',{name:/Measure 3D distance/}).click();
 await page.getByText('MEASURE / 3D').waitFor();
 await page.getByRole('button',{name:'Section tool'}).click();
 await page.getByRole('slider',{name:'Section plane offset'}).fill('1.1');
 const sectionValue=await page.getByRole('slider',{name:'Section plane offset'}).inputValue();
 if(Number(sectionValue)!==1.1)errors.push('section control state mismatch');
 await page.getByRole('button',{name:'Inspect',exact:true}).click();
 const grip=page.getByRole('separator',{name:'Resize telemetry panel'});const widthBefore=Number(await grip.getAttribute('aria-valuenow'));await grip.focus();await grip.press('ArrowLeft');const widthAfter=Number(await grip.getAttribute('aria-valuenow'));if(widthAfter!==widthBefore+20)errors.push('telemetry keyboard resizing failed');
 await page.getByRole('button',{name:'Toggle light/dark theme'}).click();
 await page.screenshot({path:'docs/native-workspace-preview/desktop-light.png',fullPage:true});
 const downloadEvent=page.waitForEvent('download');
 await page.getByTitle('Save study (⌘S)').click();
 const download=await downloadEvent;
 const data=await (await import('node:fs/promises')).readFile(await download.path(),'utf8');
 const project=JSON.parse(data);
 if(project.format!=='jet-engine-lab'||project.schema!==1||project.inputs.turbofan.engine!=='turbofan')errors.push('bad exported project');
 project.name='Roundtrip Verified Study';project.inputs.turbofan.throttle=.63;
 await page.locator('input[type="file"][aria-label="Open Jet Engine Lab project"]').setInputFiles({name:'roundtrip.jetlab.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
 await page.waitForTimeout(450);if(!(await page.locator('.studio-doc').innerText()).includes('Roundtrip Verified Study'))errors.push('imported name not displayed');
 const value=await page.getByRole('slider',{name:'Quick throttle'}).inputValue();
 if(Number(value)!==63)errors.push('project import throttle not restored: '+value);
 await page.keyboard.press('Meta+k');
 await page.getByRole('dialog',{name:'Command palette'}).waitFor();
 await page.keyboard.press('Escape');
 if(await page.getByRole('dialog',{name:'Command palette'}).count())errors.push('palette failed to close');
 await page.reload();
 await page.waitForTimeout(350);if(!(await page.locator('.studio-doc').innerText()).includes('Roundtrip Verified Study'))errors.push('recovery name not displayed');
 if(Number(await page.getByRole('slider',{name:'Quick throttle'}).inputValue())!==63)errors.push('recovery failed');
 await page.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 mobile.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mobile.goto('http://127.0.0.1:4173/#/engines/turbojet');
 await mobile.getByRole('heading',{name:'Inside the turbojet.'}).waitFor();await mobile.locator('.viewport canvas').waitFor({state:'visible'});await mobile.waitForTimeout(1000);
 await mobile.screenshot({path:'docs/native-workspace-preview/mobile-final.png',fullPage:true});
 const bounds=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth,stage:document.querySelector('.viewport-canvas')?.getBoundingClientRect().toJSON()}));
 if(bounds.scroll>bounds.width+1)errors.push('mobile overflow '+bounds.scroll);
 await mobile.close();
 console.log(JSON.stringify({success:errors.length===0,sectionValue,download:download.suggestedFilename(),projectName:project.name,mobile:bounds,errors},null,2));
 if(errors.length)process.exitCode=1;
}finally{await browser.close();}
